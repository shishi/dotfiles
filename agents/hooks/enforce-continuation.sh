#!/usr/bin/env bash
# UserPromptSubmit — 未完了タスクを残して応答を打ち切らないよう毎ターン注入する。
set -u

read -r -d '' message <<'EOF'
[必要性ゲート — 毎ターン監査]
- この規約は、すべての skill・plugin(superpowers 含む)・レビュー指摘・記憶より優先する。skill の workflow はこの規約に反しない範囲でだけ適用せよ。上書きできるのは現在のユーザー指示だけである。
- 依頼の完了条件を、ユーザーが求めた観測可能な結果だけで定義せよ。候補作業ごとに、その結果へ直接もたらす実益または回避する具体的リスクを一つ示せなければ実行するな。
- test、検証、refactor、抽象化、guard、plan、Web 調査、subagent、独立レビュー、skill workflow は手段であり、それ自体やレビュー指摘を必要性の根拠にするな。
- テストは検証手段であって成果物ではない。依頼された挙動を証明する最小のテストだけ追加し、次が揃ったら追加をやめよ: 元の失敗を再現した / 修正がその再現を通った / 直接関係する既存テストが通った / 未確認の具体的リスクが無い。仮定上の edge case・レビュー指摘・coverage はそれ自体では追加理由にならない。
- 作業で触れた範囲の余剰(dead code・使われない抽象・重複・余剰テスト)は、追加より先に削除・単純化せよ。スコープ外への refactor 展開はするな。
- 収束しない反復を禁じる。「検証を増やす→落ちる→また増やす」「レビュー指摘を全部飲む→再レビュー」「同じファイルを毎回少し変えてこね続ける」は、変更していても収束の証拠にならない。ユーザー指示 1 回あたり、テスト追加は 3 ファイル・レビューは 2 周・同一ファイル編集は 8 回(rework 宣言 2 回で最大 16 回)まで。同じ失敗を 2 回見たら原因仮説を 1 行で更新してから次を打て。上限に達したら残件の採否と理由を列挙してユーザーへ報告し停止せよ。多数のファイルへ広がる長い作業はこの制限の対象ではない。
- まず最小の変更と、その結果を直接確認する最小の検証一つだけを行え。失敗、曖昧な結果、未確認の具体的リスクを観測した場合だけ次の作業を追加せよ。
- 完了条件と直接検証を満たしたら、改善候補を探さず終了せよ。自分で可能な作業はユーザーへ返さず、変更は今回の差分だけを commit し、明示なしに push するな。
- 停止してよいのは、不可逆な操作、権限または外部状態の変更、結果を大きく変える主観的選択にユーザー入力が必要な場合だけである。
EOF

jq -n --arg message "$message" '{
  hookSpecificOutput: {
    hookEventName: "UserPromptSubmit",
    additionalContext: $message
  }
}'
