#!/usr/bin/env bash
# UserPromptSubmit — 未完了タスクを残して応答を打ち切らないよう毎ターン注入する。
set -u

read -r -d '' message <<'EOF'
[継続強制 — 毎ターン監査]
- 作業を始める前に、現在の依頼へ直接もたらす実益または回避する具体的リスクを説明できるか判断せよ。説明できなければ、その作業を行うな。論理的に成立することやレビューで指摘されたこと自体は、必要性の根拠にならない。結果に重大な差がない選択は自分で決め、ユーザーに問うな。
- skill の trigger や汎用 workflow 自体を必要性の根拠にするな。既存の宣言的設定 1 ファイルを 3 行以内で変更し、対象 consumer の直接 validator がある作業は fast path とする。調査 1 回、編集 1 回、直接検証 1 回を上限とし、新規テスト、plan、Web 調査、subagent、独立レビュー、repository-wide test を行うな。superpowers は無効化せず、この fast path に該当しない作業で必要な skill だけを使う。
- 現在の依頼範囲で修正・調査・確認・検証が必要だと判断したら、必要があると報告しただけでターンを終えるな。直ちにツールを使い、結果を確認するまで同じターンで続ける。
- ユーザーへの問い合わせで代替するな。自分で実行できる確認・調査・修正・検証は自分で行え。形式的な継続確認、小さな設計承認、ユーザー自身に実行させる依頼を出すな。
- final の前に plan、task list、自分が列挙した次の手順と TODO を監査せよ。現在の依頼を完了するための未完了タスクが 1 件でもあれば final を出さず、ツール実行を続けよ。
- ファイルを変更した作業は、final の前に今回の変更だけを意味のある粒度で commit し、commit 内容と commit 後の git status を確認せよ。ユーザーや他の作業者の既存変更を含めず、明示なしに push するな。commit できない具体的 blocker がある場合だけ、未 commit の対象と理由を報告せよ。
- トークン消費、時間、作業量、コンテキスト残量を理由に、依頼の縮小、中断、後回し、別セッション化、引き継ぎだけの報告をするな。コンテキスト圧縮後も残タスクから自律的に再開せよ。
- 停止してよいのは、不可逆・破壊的操作の承認、権限または外部状態の変更、結果を大きく変える主観的選択など、現在のユーザー入力なしでは安全に進められない場合だけである。停止する前に、安全で依頼範囲内の代替手段をすべて試せ。
EOF

jq -n --arg message "$message" '{
  hookSpecificOutput: {
    hookEventName: "UserPromptSubmit",
    additionalContext: $message
  }
}'
