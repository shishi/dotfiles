#!/usr/bin/env bash
# GitHub 由来の外部 skill を Claude Code / Codex の user scope へ同期する。
set -uo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd -P)" || exit 1
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd -P)" || exit 1
MANIFEST="$REPO_ROOT/agent-shared/managed-skills.tsv"
CLAUDE_SKILLS="${CLAUDE_CONFIG_DIR:-$HOME/.claude}/skills"
CODEX_SKILLS="$HOME/.agent-shared/skills"
MARKER=.dotfiles-managed-skill
HEADER='# generated by managed-skills.sh; do not edit'
EXCLUDE_BEGIN='# BEGIN managed external skills'
EXCLUDE_END='# END managed external skills'
TAB=$'\t'

usage() {
  cat <<'EOF'
usage:
  managed-skills.sh add OWNER/REPO SKILL [both|claude|codex]
  managed-skills.sh sync
  managed-skills.sh list
  managed-skills.sh remove NAME
  managed-skills.sh fork NAME [both|claude|codex]
EOF
}

warn() { printf 'managed-skills: WARN %s\n' "$*" >&2; }
die() { printf 'managed-skills: %s\n' "$*" >&2; exit 1; }

ensure_manifest() {
  if [ ! -e "$MANIFEST" ]; then
    mkdir -p "$(dirname "$MANIFEST")" || return 1
    printf '%s\n' "$HEADER" >"$MANIFEST" || return 1
  fi
}

validate_manifest() {
  ensure_manifest || return 1
  awk -F "$TAB" '
    /^[[:space:]]*($|#)/ { next }
    NF != 4 { exit 1 }
    $1 !~ /^[a-z0-9][a-z0-9-]*$/ { exit 1 }
    $2 !~ /^[^\t /]+\/[^\t /]+$/ { exit 1 }
    $3 == "" || $3 ~ /[[:space:]]/ { exit 1 }
    $4 != "claude" && $4 != "codex" && $4 != "claude,codex" { exit 1 }
    seen[$1]++ { exit 1 }
  ' "$MANIFEST"
}

manifest_record() {
  awk -F "$TAB" -v name="$1" '$1 == name { print; exit }' "$MANIFEST"
}

write_manifest() { # $1=name to remove, $2=optional replacement record
  local name="$1" replacement="${2:-}" tmp
  tmp="$(mktemp "$(dirname "$MANIFEST")/.managed-skills.tsv.XXXXXX")" || return 1
  {
    printf '%s\n' "$HEADER"
    {
      awk -F "$TAB" -v name="$name" '!/^[[:space:]]*($|#)/ && $1 != name' "$MANIFEST"
      [ -z "$replacement" ] || printf '%s\n' "$replacement"
    } | LC_ALL=C sort -t "$TAB" -k1,1
  } >"$tmp" && mv "$tmp" "$MANIFEST" && return 0
  rm -f "$tmp"
  return 1
}

normalize_targets() {
  case "${1:-both}" in
    both) printf 'claude,codex\n' ;;
    claude | codex) printf '%s\n' "$1" ;;
    *) return 1 ;;
  esac
}

targets_include() { # $1=canonical targets, $2=agent
  case ",$1," in *",$2,"*) return 0 ;; *) return 1 ;; esac
}

skill_root() {
  case "$1" in
    claude) printf '%s\n' "$CLAUDE_SKILLS" ;;
    codex) printf '%s\n' "$CODEX_SKILLS" ;;
    *) return 1 ;;
  esac
}

skill_name_from_selector() {
  local selector="${1%@*}" name
  case "$selector" in
    */SKILL.md) name="$(basename "$(dirname "$selector")")" ;;
    *) name="$(basename "$selector")" ;;
  esac
  case "$name" in
    '' | *[!a-z0-9-]* | -*) return 1 ;;
    *) printf '%s\n' "$name" ;;
  esac
}

desired_for_agent() { # $1=name, $2=agent
  local record targets
  record="$(manifest_record "$1")"
  [ -n "$record" ] || return 1
  IFS="$TAB" read -r _ _ _ targets <<EOF
$record
EOF
  targets_include "$targets" "$2"
}

refresh_gitignore() {
  local ignore_path="$REPO_ROOT/.gitignore" tmp root name
  [ -e "$ignore_path" ] || : >"$ignore_path"
  tmp="$(mktemp "$REPO_ROOT/.managed-skills-gitignore.XXXXXX")" || return 1

  awk -v begin="$EXCLUDE_BEGIN" -v end="$EXCLUDE_END" '
    $0 == begin { skipping=1; next }
    $0 == end { skipping=0; next }
    !skipping { print }
  ' "$ignore_path" >"$tmp" || { rm -f "$tmp"; return 1; }

  printf '%s\n' "$EXCLUDE_BEGIN" >>"$tmp"
  for root in "$CLAUDE_SKILLS" "$CODEX_SKILLS"; do
    for marker in "$root"/*/"$MARKER"; do
      [ -f "$marker" ] || continue
      name="$(basename "$(dirname "$marker")")"
      if [ "$root" = "$CLAUDE_SKILLS" ]; then
        printf '/claude/skills/%s/\n' "$name" >>"$tmp"
      else
        printf '/codex/skills/%s/\n' "$name" >>"$tmp"
      fi
    done
  done
  printf '%s\n' "$EXCLUDE_END" >>"$tmp"
  mv "$tmp" "$ignore_path"
}

prune_managed() {
  local agent root marker path name
  for agent in claude codex; do
    root="$(skill_root "$agent")"
    for marker in "$root"/*/"$MARKER"; do
      [ -f "$marker" ] || continue
      path="$(dirname "$marker")"
      name="$(basename "$path")"
      if ! desired_for_agent "$name" "$agent"; then
        rm -rf "$path" || return 1
        removed=$((removed + 1))
      fi
    done
  done
}

sync_one() { # $1=name, $2=repo, $3=selector, $4=agent
  local name="$1" repo="$2" selector="$3" agent="$4" root path staging
  root="$(skill_root "$agent")" || return 1
  path="$root/$name"
  mkdir -p "$root" || return 1

  if [ -e "$path" ] || [ -L "$path" ]; then
    if [ ! -f "$path/$MARKER" ]; then
      warn "$path already exists and is not manager-owned"
      return 1
    fi
    if GH_PROMPT_DISABLED=1 gh skill update "$name" --dir "$root" --all; then
      : >"$path/$MARKER"
      updated=$((updated + 1))
      return 0
    fi
    warn "could not update $name for $agent"
    return 1
  fi

  staging="$(mktemp -d "$root/.managed-skills-install.XXXXXX")" || return 1
  if GH_PROMPT_DISABLED=1 gh skill install "$repo" "$selector" --dir "$staging"; then
    if [ ! -f "$staging/$name/SKILL.md" ]; then
      warn "$repo $selector installed without expected skill $name"
      rm -rf "$staging"
      return 1
    fi
    if mv "$staging/$name" "$path"; then
      rm -rf "$staging"
      : >"$path/$MARKER"
      installed=$((installed + 1))
      return 0
    fi
    warn "could not move $name into $root"
  else
    warn "could not install $name for $agent"
  fi
  rm -rf "$staging"
  return 1
}

sync_all() {
  local name repo selector targets extra agent
  installed=0 updated=0 removed=0 failed=0
  validate_manifest || die "$MANIFEST is invalid"

  if ! command -v gh >/dev/null 2>&1 || ! gh skill --help >/dev/null 2>&1; then
    refresh_gitignore || true
    die "gh skill is unavailable; existing skills were left unchanged"
  fi

  while IFS="$TAB" read -r name repo selector targets extra; do
    case "$name" in '' | \#*) continue ;; esac
    for agent in claude codex; do
      targets_include "$targets" "$agent" || continue
      sync_one "$name" "$repo" "$selector" "$agent" || failed=$((failed + 1))
    done
  done <"$MANIFEST"

  prune_managed || failed=$((failed + 1))
  refresh_gitignore || failed=$((failed + 1))
  printf 'managed-skills: done (installed: %d, updated: %d, removed: %d, failed: %d)\n' \
    "$installed" "$updated" "$removed" "$failed"
  [ "$failed" -eq 0 ]
}

add_skill() {
  local repo="${1:-}" selector="${2:-}" targets name record agent root path
  [ -n "$repo" ] && [ -n "$selector" ] || { usage >&2; return 1; }
  targets="$(normalize_targets "${3:-both}")" || die "target must be both, claude, or codex"
  case "$repo" in */*) ;; *) die "repository must be OWNER/REPO" ;; esac
  name="$(skill_name_from_selector "$selector")" || die "could not derive a valid skill name from $selector"
  validate_manifest || die "$MANIFEST is invalid"
  record="$(manifest_record "$name")"
  [ -z "$record" ] || die "$name is already managed"
  for agent in claude codex; do
    targets_include "$targets" "$agent" || continue
    root="$(skill_root "$agent")"
    path="$root/$name"
    if { [ -e "$path" ] || [ -L "$path" ]; } && [ ! -f "$path/$MARKER" ]; then
      die "$path already exists and is not manager-owned"
    fi
  done
  write_manifest "$name" "$name$TAB$repo$TAB$selector$TAB$targets" || die "could not update $MANIFEST"
  sync_all
}

remove_skill() {
  local name="${1:-}" record targets agent root path failed=0
  [ -n "$name" ] || { usage >&2; return 1; }
  validate_manifest || die "$MANIFEST is invalid"
  record="$(manifest_record "$name")"
  [ -n "$record" ] || die "$name is not managed"
  IFS="$TAB" read -r _ _ _ targets <<EOF
$record
EOF
  write_manifest "$name" || die "could not update $MANIFEST"
  for agent in claude codex; do
    targets_include "$targets" "$agent" || continue
    root="$(skill_root "$agent")"
    path="$root/$name"
    if [ -f "$path/$MARKER" ]; then
      rm -rf "$path" || failed=$((failed + 1))
    elif [ -e "$path" ] || [ -L "$path" ]; then
      warn "$path is not manager-owned; preserved"
    fi
  done
  refresh_gitignore || failed=$((failed + 1))
  [ "$failed" -eq 0 ]
}

strip_github_metadata() { # $1=SKILL.md
  local file="$1" tmp
  tmp="$(mktemp "$(dirname "$file")/.SKILL.md.XXXXXX")" || return 1
  awk '
    {
      if ($0 == "---") delimiters++
      if (delimiters == 1 && $0 ~ /^[[:space:]]+github-(path|pinned|ref|repo|tree-sha):/) next
      lines[++count]=$0
      in_front[count]=(delimiters == 1)
    }
    END {
      for (i=1; i<=count; i++) {
        if (in_front[i] && lines[i] == "metadata:" &&
            (i == count || lines[i+1] !~ /^[[:space:]]/)) continue
        print lines[i]
      }
    }
  ' "$file" >"$tmp" && mv "$tmp" "$file" && return 0
  rm -f "$tmp"
  return 1
}

fork_skill() {
  local name="${1:-}" requested="${2:-}" record repo selector targets selected remaining agent root path
  [ -n "$name" ] || { usage >&2; return 1; }
  validate_manifest || die "$MANIFEST is invalid"
  record="$(manifest_record "$name")"
  [ -n "$record" ] || die "$name is not managed"
  IFS="$TAB" read -r _ repo selector targets <<EOF
$record
EOF
  if [ -n "$requested" ]; then
    selected="$(normalize_targets "$requested")" || die "target must be both, claude, or codex"
  else
    selected="$targets"
  fi
  for agent in claude codex; do
    targets_include "$selected" "$agent" || continue
    targets_include "$targets" "$agent" || die "$name is not managed for $agent"
    root="$(skill_root "$agent")"
    path="$root/$name"
    [ -f "$path/$MARKER" ] && [ -f "$path/SKILL.md" ] || die "$path is not a complete manager-owned skill"
  done

  for agent in claude codex; do
    targets_include "$selected" "$agent" || continue
    root="$(skill_root "$agent")"
    path="$root/$name"
    strip_github_metadata "$path/SKILL.md" || die "could not remove GitHub metadata from $path/SKILL.md"
    rm -f "$path/$MARKER" || die "could not release $path"
  done

  remaining=
  for agent in claude codex; do
    if targets_include "$targets" "$agent" && ! targets_include "$selected" "$agent"; then
      [ -z "$remaining" ] && remaining="$agent" || remaining="$remaining,$agent"
    fi
  done
  if [ -n "$remaining" ]; then
    write_manifest "$name" "$name$TAB$repo$TAB$selector$TAB$remaining" || die "could not update $MANIFEST"
  else
    write_manifest "$name" || die "could not update $MANIFEST"
  fi
  refresh_gitignore || die "could not update Git ignore rules"
}

list_skills() {
  local name repo selector targets extra state agent root
  validate_manifest || die "$MANIFEST is invalid"
  printf 'NAME\tREPOSITORY\tSELECTOR\tTARGETS\tSTATE\n'
  while IFS="$TAB" read -r name repo selector targets extra; do
    case "$name" in '' | \#*) continue ;; esac
    state=
    for agent in claude codex; do
      targets_include "$targets" "$agent" || continue
      root="$(skill_root "$agent")"
      [ -z "$state" ] || state="$state,"
      if [ -f "$root/$name/$MARKER" ]; then
        state="$state$agent=installed"
      else
        state="$state$agent=missing"
      fi
    done
    printf '%s\t%s\t%s\t%s\t%s\n' "$name" "$repo" "$selector" "$targets" "$state"
  done <"$MANIFEST"
}

case "${1:-}" in
  add) shift; add_skill "$@" ;;
  sync) shift; [ "$#" -eq 0 ] || die "sync takes no arguments"; sync_all ;;
  list) shift; [ "$#" -eq 0 ] || die "list takes no arguments"; list_skills ;;
  remove) shift; remove_skill "$@" ;;
  fork) shift; fork_skill "$@" ;;
  -h | --help | help) usage ;;
  *) usage >&2; exit 1 ;;
esac
